bool petBitmapPixel(const PetBitmapFrame& frame, uint8_t x, uint8_t y) {
  if (x >= frame.width || y >= frame.height || frame.bits == nullptr) {
    return false;
  }
  const uint16_t bitIndex = static_cast<uint16_t>(y) * frame.width + x;
  const uint8_t nibble = hexValue(frame.bits[bitIndex / 4]);
  return (nibble & (1 << (3 - (bitIndex % 4)))) != 0;
}

const PetBitmapFrame& bitmapForMode(PetMode mode, uint32_t tickMs) {
  const bool phase = ((tickMs / 500) % 2) == 0;
  switch (mode) {
    case PetMode::Sleep:
      return phase ? kGugugagaSleepA : kGugugagaSleepB;
    case PetMode::Busy:
      return phase ? kGugugagaBusyA : kGugugagaBusyB;
    case PetMode::Attention:
      return phase ? kGugugagaAttentionA : kGugugagaAttentionB;
    case PetMode::Celebrate:
      return phase ? kGugugagaCelebrateA : kGugugagaCelebrateB;
    case PetMode::Error:
      return phase ? kGugugagaErrorA : kGugugagaErrorB;
    case PetMode::Tired:
      return phase ? kGugugagaSleepB : kGugugagaSleepA;
    case PetMode::Charging:
      return phase ? kGugugagaBusyB : kGugugagaIdleA;
    case PetMode::Idle:
    default:
      return phase ? kGugugagaIdleA : kGugugagaIdleB;
  }
}

