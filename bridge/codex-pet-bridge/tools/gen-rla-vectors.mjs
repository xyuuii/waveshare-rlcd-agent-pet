#!/usr/bin/env node
// Writes the cross-language test vector used by the firmware's native tests.
// The animation mixes key, delta and repeat frames; the expected decoded
// bitmaps are written next to the encoded file so C++ can compare byte-exact.
//
//   node tools/gen-rla-vectors.mjs ../../firmware/agent_pet_display/test/native/test_anim_codec/anim_vectors.h

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { RlaEncoder, frameBytes, stride } from "../src/rla-codec.js";

function drawBox(bitmap, width, x0, y0, w, h) {
  for (let y = y0; y < y0 + h; y += 1) {
    for (let x = x0; x < x0 + w; x += 1) bitmap[y * stride(width) + (x >> 3)] |= 1 << (x & 7);
  }
}

export function boxAnimation() {
  const width = 64;
  const height = 24;
  const encoder = new RlaEncoder({ width, height, fpsX100: 1000, keyframeInterval: 0 });
  const frames = [];
  const push = (bitmap) => {
    frames.push(bitmap.slice());
    encoder.addFrame(bitmap);
  };
  for (let index = 0; index < 5; index += 1) {
    const bitmap = new Uint8Array(frameBytes(width, height));
    drawBox(bitmap, width, 8 + index, 4, 30, 14);  // 1 px steps -> thin XOR deltas
    push(bitmap);
  }
  push(frames[frames.length - 1]);  // exact repeat
  const dotted = frames[frames.length - 1].slice();
  dotted[0] |= 1;  // a single pixel -> tiny delta
  push(dotted);
  return { width, height, frames, bytes: encoder.finish(), stats: encoder.stats };
}

function hexLines(bytes) {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push(`    ${Array.from(bytes.subarray(i, i + 16), (b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ")},`);
  }
  return lines.join("\n");
}

function toHeader({ width, height, frames, bytes, stats }) {
  const perFrame = frameBytes(width, height);
  const expected = new Uint8Array(perFrame * frames.length);
  frames.forEach((frame, index) => expected.set(frame, index * perFrame));
  return `#pragma once
// Generated by bridge/codex-pet-bridge/tools/gen-rla-vectors.mjs — do not edit.
// Frame types: ${JSON.stringify(stats)}
#include <stdint.h>

static constexpr uint16_t kAnimVectorWidth = ${width};
static constexpr uint16_t kAnimVectorHeight = ${height};
static constexpr uint32_t kAnimVectorFrames = ${frames.length};
static const uint8_t kAnimVectorFile[${bytes.length}] = {
${hexLines(bytes)}
};
static const uint8_t kAnimVectorExpected[${expected.length}] = {
${hexLines(expected)}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = process.argv[2];
  if (!target) {
    console.error("usage: gen-rla-vectors.mjs <output.h>");
    process.exit(2);
  }
  const animation = boxAnimation();
  writeFileSync(target, toHeader(animation));
  console.log(`wrote ${target} (${animation.bytes.length} bytes, ${JSON.stringify(animation.stats)})`);
}
